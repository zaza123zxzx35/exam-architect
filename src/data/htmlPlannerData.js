export function getPlanDateByIndex(dayIndex) {
  const start = new Date(Date.UTC(2026, 9, 12))
  const d = new Date(start)
  d.setUTCDate(start.getUTCDate() + dayIndex)
  const y = d.getUTCFullYear()
  const m = String(d.getUTCMonth() + 1).padStart(2, '0')
  const day = String(d.getUTCDate()).padStart(2, '0')
  return `${y}-${m}-${day}`
}

export function getDayIndexForDate(isoDate) {
  const [y, m, d] = isoDate.split('-').map(Number)
  const cur = Date.UTC(y, m - 1, d)
  const start = Date.UTC(2026, 9, 12)
  return Math.floor((cur - start) / 86400000)
}

export function bangkokTodayIso(now = new Date()) {
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Bangkok' }).format(now)
}
